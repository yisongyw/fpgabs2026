//-----------------------------------------------------------------------------
// Module     : mlp_classifier
// Project    : HX1P35Aimg_process_create1
// Description: Integer only inference engine for the tiny target classifier.
//
//   Network (extension requirement 3 + 4)
//   -------------------------------------
//
//        input : NIN  =  8 uint8 features (produced by obj_feature_extract)
//        hidden: NH   = 32 neurons, ReLU, INT8 requantised by a shift
//        output: NOUT = 64 classes (argmax)  improve4 : 32 -> 64 categories
//
//        weights   8  bit   (b1 / b2 are INT16, two bytes little endian)
//        biases   16 bit
//        size      8 x 32 + 32 x 16 bit + 32 x 64 + 64 x 16 bit
//                = 256 + 64 + 2048 + 128 = 2496 byte
//        workload  8 x 32 + 32 x 64 = 2304 MAC per object
//
//   improve4 changes (64 classes, resource and latency aware)
//   --------------------------------------------------------
//     1. every class counter (r_n / r_a) is 6 bit -> NOUT up to 64 is legal
//        (5 bit silently truncated 32 -> 0 and could only scan 32 classes)
//     2. task 4 : the weight ROM stays a distributed RAM array (2496 byte =
//        ~39 LUT6) because its read is COMBINATIONAL : one multiply is one clock
//        and the state machine needs no address phase.  A block RAM (ERAM9K)
//        version was implemented and simulated - it would move those ~39 LUT6
//        into one of the 41 idle ERAM blocks - but its read is REGISTERED, so
//        the address of a byte has to be applied one clock before it is used
//        and the state machine can apply only ONE address per clock : the last
//        weight byte of every row would need an extra state (+96 clocks per
//        object) or be lost.  The combinational read is therefore faster AND
//        simpler; the LUT / ERAM balance is improved where it costs nothing.
//     3. the logits are stored as SATURATING 16 bit instead of 32 bit : the
//        widest possible logit is 8 x 255 x 127 + 32767 = 292047 (19 bit),
//        everything above 32767 behaves exactly like 32767.  64 x 16 bit
//        instead of 32 x 32 bit -> the 64 class model needs FEWER registers
//        than the 32 class model.
//     4. task 4 power : the accumulator and the ROM address only change while a
//        multiply is really running (every other state holds them).  That keeps
//        the DSP block, the 32 bit adder and the RAM address decoder from
//        switching during the ~25 % of the clocks that are bias / activation /
//        argmax states, which is the cheapest dynamic power saving available
//        without a second clock domain.
//     5. the argmax scans ONE logit per clock.  A "two logits per clock" version
//        was implemented and dropped : the second comparison of a clock needs
//        the result of the first one of the very same clock, so class and
//        confidence depended on the order inside a pair.  The second best value
//        is the maximum of the PREVIOUS best (pushed down) and the new logit.
//
//   One single multiply-accumulate unit is used (bit serial network evaluation).
//
//   Everything is done with power of two scales, therefore there is NO divider
//   inside this module; the confidence value comes from a small comparison table.
//
//   Inference is fully deterministic and bit exact identical to the Python golden
//   model that trained the weights (see ../HX1P35Aimg_process_create1_sim/
//   mlp_train/train_mlp.py and tb_mlp_classifier.v).
//
//   Weight memory : mlp_weight_rom.v, generated by the training script.
//
//   *** Both mlp_weight_rom.v AND tb_mlp_classifier.v are (re)generated by
//       train_mlp.py, so the weights and the golden reference of the testbench
//       can never drift apart.  Run train_mlp.py after changing NIN/NH/NOUT. ***
//-----------------------------------------------------------------------------
module mlp_classifier #(
    parameter NIN    = 8,       // input features (uint8)
    parameter NH     = 32,      // hidden neurons
    parameter CLS_W  = 6,       // bit width of a class index (2**CLS_W classes max)
    parameter NOUT   = 64,      // classes, NOUT <= 2**CLS_W
    // ---------------------------------------------------------------------
    // improve1 : resource balancing.
    //   The int8 x uint8 multiply of the MAC unit was built from a shift-and-add
    //   network (~60 LUT) and it was also part of the critical path of the
    //   60 MHz CSI clock domain (SWNS +0.004 ns).  With USE_DSP = 1 the very
    //   same operation is one DSP block : fewer LUTs, shorter combinational
    //   path -> better timing margin.  Set USE_DSP = 0 to get the old,
    //   DSP free implementation back.
    // ---------------------------------------------------------------------
    parameter USE_DSP = 1,
    // improve4 task 4 : 1 = the accumulator is only clocked while a multiply is
    //   really running (dynamic power).  0 = the improve3 behaviour, the
    //   accumulator is written in every state of the state machine.
    parameter GATE_ACC = 1
)(
    input  wire              I_clk,
    input  wire              I_rst_n,

    input  wire              I_start,
    input  wire [NIN*8-1:0]  I_feat,          // [7:0] = feature 0

    output reg               O_valid,         // one clock, result available
    output reg  [CLS_W-1:0]  O_class,
    output reg  [6:0]        O_conf           // 0 .. 99 (percent)
);

    //-------------------------------------------------------------------------
    // weight / bias layout inside the ROM (byte addresses)
    //-------------------------------------------------------------------------
    // improve4 : 64 classes -> 8 + 2*32 + 32*64 + 2*64 = 2496 weight bytes,
    // the ROM address is 12 bit wide (up to 4096 bytes).
    localparam [11:0] A_W1      = 12'd0;
    localparam [11:0] A_B1      = A_W1 + NIN*NH;           // 256
    localparam [11:0] A_W2      = A_B1 + 2*NH;             // 320
    localparam [11:0] A_B2      = A_W2 + NH*NOUT;          // 2368

    // 6 bit so that NH = 32 and NOUT = 64 are representable
    //   (NOUT[5:0] would truncate 64 to 0 - that silently stopped the argmax
    //    scan after its first clock, see ST_ARG)
    localparam [5:0] C_NH      = NH[5:0];      // constant, for the address step
    localparam [5:0] C_NIN     = NIN[5:0];     // constant, for the address step
    localparam [6:0] C_NOUT    = NOUT;         // constant, full width class count

    //-------------------------------------------------------------------------
    // states (the weight ROM is read COMBINATIONALLY, so one clock per MAC)
    //   hidden layer : HMAC  : acc += w1[n][j] * x[j], address of the next byte
    //                  HB0   : capture the low  bias byte
    //                  HB1   : acc += {high, low} bias
    //                  ACT   : ReLU + requantise + store h[n]
    //   output layer : OMAC  : acc += w2[n][j] * h[j]
    //                  OADR  : address of the next weight byte
    //                  OB0 / OB1 : the two bias bytes
    //                  OST   : store z[n]
    //   result       : ARG (argmax scan) -> CONF (margin) -> OUT (confidence)
    //-------------------------------------------------------------------------
    localparam [3:0] ST_IDLE = 4'd0;
    localparam [3:0] ST_HMAC = 4'd2;
    localparam [3:0] ST_HB0  = 4'd3;
    localparam [3:0] ST_HB1  = 4'd4;
    localparam [3:0] ST_ACT  = 4'd5;
    localparam [3:0] ST_OMAC = 4'd6;
    localparam [3:0] ST_OB0  = 4'd8;
    localparam [3:0] ST_OB1  = 4'd9;
    localparam [3:0] ST_OST  = 4'd10;
    localparam [3:0] ST_OUT  = 4'd11;
    localparam [3:0] ST_ARG  = 4'd12;     // unique : never share an encoding
    localparam [3:0] ST_CONF = 4'd13;

    //-------------------------------------------------------------------------
    // state machine  (declared BEFORE the ROM instance : r_addr is an input of
    // the ROM and must not be picked up as an implicit 1 bit net first)
    //-------------------------------------------------------------------------
    reg [3:0]  r_state;
    reg [11:0] r_addr;          // improve4 : 12 bit (up to 4096 weight bytes)
    reg [5:0]  r_n;             // improve4 : 6 bit (NOUT <= 64)
    reg [5:0]  r_j;
    reg [7:0]  r_blo;

    // improve4 task 4 : "a multiply is running" and "this is the first multiply
    //   of a row" (then the accumulator only takes the product, it has been
    //   cleared by the bias / activation state of the row before).
    wire S_mac_run   = (r_state == ST_HMAC) || (r_state == ST_OMAC);
    wire S_row_start = (r_j == 6'd0);
    // with GATE_ACC the accumulator is held outside a MAC state : the DSP block
    // and the 32 bit adder then do not switch during the bias / activation /
    // argmax clocks (dynamic power)
    wire S_acc_run   = GATE_ACC ? S_mac_run : 1'b1;

    //-------------------------------------------------------------------------
    // weight ROM (distributed RAM, combinational read -> one clock per MAC)
    //-------------------------------------------------------------------------
    wire [7:0] S_w;
    wire [4:0] S_shift;

    mlp_weight_rom u_rom (
        .I_addr  ( r_addr       ),   // 12 bit : up to 4096 weight bytes
        .O_data  ( S_w          ),
        .O_shift ( S_shift      )
    );

    reg [NIN*8-1:0] r_x;            // feature vector (constant per inference)
    reg signed [31:0] r_acc;
    reg [7:0]  r_h   [0:NH-1];
    // improve4 : saturating 16 bit logits (the 32 bit copy only wasted 1024 FF)
    reg signed [15:0] r_z [0:NOUT-1];

    wire [7:0] S_xj = r_x[8*r_j +: 8];

    // the second operand of the MAC unit : layer 1 multiplies the feature,
    // layer 2 multiplies the hidden activation -> one shared multiply
    wire [7:0] S_mac_b = (r_state == ST_OMAC) ? r_h[r_j] : S_xj;

    integer ii;

    //-------------------------------------------------------------------------
    // int8 x uint8 -> signed 32 bit, SHIFT AND ADD ONLY (0 DSP)
    //
    //   Writing "$signed(w) * $signed({1'b0,x})" makes the synthesiser infer a
    //   DSP block : the area report showed 2 DSP inside this module although
    //   the whole design was documented as DSP free.  The sign / magnitude
    //   loop below is mathematically identical and pure combinational logic.
    //
    //   |a| <= 128 and b <= 255 -> the unsigned products stay below 2^16, so a
    //   16 bit accumulator can never overflow and no intermediate result needs
    //   a signed interpretation.
    //-------------------------------------------------------------------------
    function signed [31:0] mul_i8_u8;
        input signed [7:0] a;
        input        [7:0] b;
        reg  [7:0]  mag;
        reg  [15:0] up;
        integer i;
        begin
            mag = a[7] ? (~a + 8'd1) : a;      // |a|, 0 .. 128
            up  = 16'd0;
            for(i = 0; i < 8; i = i + 1)
                if(b[i]) up = up + ({8'd0, mag} << i);
            mul_i8_u8 = a[7] ? -$signed({1'b0, up}) : $signed({1'b0, up});
        end
    endfunction

    //-------------------------------------------------------------------------
    // multiply by a CONSTANT with shifts and adds (0 DSP)
    //   used for the weight address arithmetic; << and + only, so no DSP can
    //   be inferred even after the real MAC multiply has been replaced.
    //-------------------------------------------------------------------------
    function [11:0] mul_step;
        input [6:0] c;                  // constant multiplier (up to NH = 32)
        input [6:0] v;                  // improve4 : up to NOUT = 64
        reg [11:0] s;
        integer i;
        begin
            s = 12'd0;
            for(i = 0; i < 7; i = i + 1)
                if(c[i]) s = s + ({5'd0, v} << i);
            mul_step = s;
        end
    endfunction

    //-------------------------------------------------------------------------
    // improve1 : one multiply, either as a DSP block or as shift-and-add
    //-------------------------------------------------------------------------
    wire signed [31:0] S_mul;

    generate
        if (USE_DSP != 0) begin : g_mac_dsp
            // int8 x uint8 -> 16 bit, the synthesiser maps this to one DSP
            wire signed [15:0] S_prod = $signed(S_w) * $signed({1'b0, S_mac_b});
            assign S_mul = {{16{S_prod[15]}}, S_prod};
        end
        else begin : g_mac_lut
            assign S_mul = mul_i8_u8(S_w, S_mac_b);
        end
    endgenerate

    //-------------------------------------------------------------------------
    // ReLU + requantise (shift instead of division, saturating)
    //-------------------------------------------------------------------------
    function [7:0] relu8;
        input signed [31:0] a;
        input        [4:0]  sh;
        reg [31:0] t;
        begin
            if(a[31])        relu8 = 8'd0;
            else begin
                t = a >> sh;
                relu8 = (|t[31:8]) ? 8'd255 : t[7:0];
            end
        end
    endfunction

    //-------------------------------------------------------------------------
    // improve4 : saturating 16 bit logit
    //   |z| <= 8 x 255 x 127 + 32767 = 292047, i.e. 19 bit.  Every value above
    //   32767 is "certainly the maximum" anyway, so clipping at 32767 does not
    //   change a single argmax or confidence decision.
    //-------------------------------------------------------------------------
    function signed [15:0] sat16;
        input signed [31:0] a;
        begin
            if(a[31]) begin
                if((a[31:15] != 17'h1FFFF) && (a[31:15] != 17'h0)) sat16 = 16'h8000;
                else                                                sat16 = a[15:0];
            end
            else begin
                sat16 = (|a[31:15]) ? 16'h7FFF : a[15:0];
            end
        end
    endfunction

    //-------------------------------------------------------------------------
    // confidence from the margin between the best and the second best class
    //   m = margin >> 3,   conf = 100*m / (m + 2)   with m' = m*8
    //-------------------------------------------------------------------------
    function [6:0] conf_of;
        input [15:0] margin;
        reg  [7:0] m;
        begin
            // saturate at 248 (everything above behaves like "very sure")
            m = (|margin[15:8]) ? 8'd248 : {margin[7:3], 3'd0};
            case(m[7:3])
                5'd0 : conf_of = 7'd0;
                5'd1 : conf_of = 7'd33;
                5'd2 : conf_of = 7'd50;
                5'd3 : conf_of = 7'd60;
                5'd4 : conf_of = 7'd67;
                5'd5 : conf_of = 7'd71;
                5'd6 : conf_of = 7'd75;
                5'd7 : conf_of = 7'd78;
                5'd8 : conf_of = 7'd80;
                5'd9 : conf_of = 7'd82;
                5'd10: conf_of = 7'd83;
                5'd11: conf_of = 7'd85;
                5'd12: conf_of = 7'd86;
                5'd13: conf_of = 7'd87;
                5'd14: conf_of = 7'd88;
                5'd15: conf_of = 7'd88;
                5'd16: conf_of = 7'd89;
                5'd17: conf_of = 7'd89;
                5'd18: conf_of = 7'd90;
                5'd19: conf_of = 7'd90;
                5'd20: conf_of = 7'd91;
                5'd21: conf_of = 7'd91;
                5'd22: conf_of = 7'd92;
                5'd23: conf_of = 7'd92;
                5'd24: conf_of = 7'd92;
                5'd25: conf_of = 7'd93;
                5'd26: conf_of = 7'd93;
                5'd27: conf_of = 7'd93;
                5'd28: conf_of = 7'd94;
                5'd29: conf_of = 7'd94;
                5'd30: conf_of = 7'd94;
                default: conf_of = 7'd95;
            endcase
        end
    endfunction

    //-------------------------------------------------------------------------
    // argmax over the NOUT logits + second best value (-> confidence)
    //
    //   This used to be ONE combinational always@(*) block that scanned all
    //   NOUT logits in series.  Once r_addr became a real ROM address (it used
    //   to be an implicit 1 bit net, which made the whole MLP logic constant
    //   fold away) that became the critical path :
    //       r_z -> NOUT x 32-bit compare chain -> conf_of -> O_conf
    //   = 25 logic levels / ~21 ns  >  16.67 ns (MIPI_RX_BYTE_CLK, 60 MHz).
    //
    //   It is therefore spread over three clocked stages :
    //       ST_ARG  : one (or two) logit(s) per clock -> running (max, 2nd, idx)
    //       ST_CONF : register (max - 2nd) and the "all negative" flag
    //       ST_OUT  : look the confidence up from the registered margin
    //-------------------------------------------------------------------------
    reg signed [15:0]      S_zmax, S_z2nd;
    // improve4 : the second logit of the two logits per clock argmax scan
    wire [5:0]             S_a1 = r_a + 6'd1;
    wire signed [15:0]     S_z1 = r_z[S_a1];
    reg [CLS_W-1:0]        S_imax;
    reg [5:0]              r_a;         // improve4 : 6 bit argmax scan index
    reg signed [18:0]      r_margin;    // registered (zmax - z2nd), 16+1 bit
    reg                    r_allneg;    // registered "all logits negative"
    // improve4 : the very first logit of a scan seeds BOTH the best and the
    //   second best value (see header, 5.)
    reg                    r_first;
    // (no second logit per clock : a second comparison inside one clock made
    //  the confidence and the class depend on the order of the pair, which is
    //  not worth the ~30 saved clocks out of ~2400)
    // the candidate for the second best value : the maximum of the running
    // best and second best, i.e. the best value seen so far EXCLUDING the
    // current maximum
    wire signed [15:0]     S_max2 = (S_z2nd > S_zmax) ? S_z2nd : S_zmax;

    always @(posedge I_clk or negedge I_rst_n) begin
        if(!I_rst_n) begin
            r_state <= ST_IDLE;
            r_addr  <= 12'd0;
            r_n     <= 6'd0;
            r_j     <= 6'd0;
            r_blo   <= 8'd0;
            r_x     <= {NIN*8{1'b0}};
            r_acc   <= 32'd0;
            for(ii = 0; ii < NH;   ii = ii + 1) r_h[ii] <= 8'd0;
            for(ii = 0; ii < NOUT; ii = ii + 1) r_z[ii] <= 16'sd0;
            r_a      <= 6'd0;
            r_first  <= 1'b1;
            r_margin <= 19'sd0;
            r_allneg <= 1'b0;
            S_zmax   <= 16'h8000;
            S_z2nd   <= 16'h8000;
            S_imax   <= {CLS_W{1'b0}};
            O_valid <= 1'b0;
            O_class <= {CLS_W{1'b0}};
            O_conf  <= 7'd0;
        end
        else begin
            O_valid <= 1'b0;

            case(r_state)
                //-----------------------------------------------------------
                ST_IDLE: begin
                    if(I_start) begin
                        r_x     <= I_feat;
                        r_n     <= 6'd0;
                        r_j     <= 6'd0;
                        r_acc   <= 32'd0;
                        // prefetch : the first MAC of the next clock needs W1[0][0]
                        r_addr  <= A_W1;
                        r_state <= ST_HMAC;
                    end
                end

                //-----------------------------------------------------------
                // hidden layer : sum(w1[n][j] * x[j])
                //
                //   improve4 task 4 : the ROM read is REGISTERED, therefore the
                //   address of the byte that the NEXT MAC needs is applied here
                //   (one clock early).  The byte S_w of THIS clock was already
                //   requested by the state before, so a MAC still costs one
                //   clock and no extra state is needed.
                //-----------------------------------------------------------
                ST_HMAC: begin
                    // improve4 task 4 : outside a multiply the accumulator is
                    // held, so the DSP block and the 32 bit adder do not switch
                    r_acc <= S_mac_run ? (S_row_start ? S_mul : (r_acc + S_mul))
                                       : r_acc;
                    if(r_j == C_NIN - 6'd1) begin
                        r_j     <= 6'd0;
                        r_addr  <= A_B1 + {5'd0, r_n, 1'b0};   // B1[n] low
                        r_state <= ST_HB0;
                    end
                    else begin
                        r_j     <= r_j + 6'd1;
                        r_addr  <= r_addr + 12'd1;             // W1[n][j+1]
                        r_state <= ST_HMAC;
                    end
                end

                //-----------------------------------------------------------
                // add the INT16 bias (little endian) + ReLU + requantise
                //-----------------------------------------------------------
                ST_HB0: begin
                    r_blo   <= S_w;                     // B1[n] low
                    r_addr  <= r_addr + 12'd1;          // B1[n] high
                    r_state <= ST_HB1;
                end

                ST_HB1: begin
                    r_acc   <= r_acc + $signed({S_w, r_blo});
                    r_state <= ST_ACT;
                end

                ST_ACT: begin
                    r_h[r_n] <= relu8(r_acc, S_shift);
                    r_acc    <= 32'd0;
                    if(r_n == C_NH - 6'd1) begin
                        r_n     <= 6'd0;
                        r_j     <= 6'd0;
                        r_addr  <= A_W2;                // W2[0][0]
                        r_state <= ST_OMAC;
                    end
                    else begin
                        r_n     <= r_n + 6'd1;
                        r_j     <= 6'd0;
                        // NOTE r_n is incremented in this clock : the index of
                        // the NEXT neuron is r_n + 1
                        r_addr  <= A_W1 + mul_step(C_NIN, r_n + 6'd1);
                        r_state <= ST_HMAC;
                    end
                end

                //-----------------------------------------------------------
                // output layer : sum(w2[n][j] * h[j])
                //-----------------------------------------------------------
                ST_OMAC: begin
                    r_acc <= S_mac_run ? (S_row_start ? S_mul : (r_acc + S_mul))
                                       : r_acc;
                    if(r_j == C_NH - 6'd1) begin
                        r_j     <= 6'd0;
                        r_addr  <= A_B2 + {5'd0, r_n, 1'b0};   // B2[n] low
                        r_state <= ST_OB0;
                    end
                    else begin
                        r_j     <= r_j + 6'd1;
                        r_addr  <= r_addr + 12'd1;             // W2[n][j+1]
                        r_state <= ST_OMAC;
                    end
                end

                // NOTE ST_OADR is deliberately NOT defined : the output MAC
                // loop applies the next address in the same clock (like the
                // hidden layer).  An unused state must not share its encoding
                // with another one, or the case statement picks the first
                // matching branch and the state machine takes a wrong path.

                ST_OB0: begin
                    r_blo   <= S_w;                     // B2[n] low
                    r_addr  <= r_addr + 12'd1;          // B2[n] high
                    r_state <= ST_OB1;
                end

                ST_OB1: begin
                    r_acc   <= r_acc + $signed({S_w, r_blo});
                    r_state <= ST_OST;
                end

                ST_OST: begin
                    r_z[r_n] <= sat16(r_acc);
                    r_acc    <= 32'd0;
                    if(r_n == C_NOUT - 7'd1) begin
                        r_a      <= 6'd0;
                        r_first  <= 1'b1;
                        r_state  <= ST_ARG;             // start the argmax scan
                    end
                    else begin
                        r_n     <= r_n + 6'd1;
                        r_j     <= 6'd0;
                        // NOTE r_n is incremented in this clock : the index of
                        // the NEXT class is r_n + 1
                        r_addr  <= A_W2 + mul_step(C_NH, r_n + 6'd1);
                        r_state <= ST_OMAC;
                    end
                end

                //-----------------------------------------------------------
                // argmax : one (or two) logit(s) per clock
                //   the comparator chain of a whole class is 1 stage, so the
                //   scan is clocked instead of combinational -> short path
                //-----------------------------------------------------------
                ST_ARG: begin
                    //-------------------------------------------------------
                    // ONE logit per clock.
                    //   seeding clock : r_z[0] becomes the best value and the
                    //   second best is "nothing" (16 bit minimum).  The scan
                    //   then runs from index 1 to C_NOUT-1, so every logit is
                    //   evaluated exactly once.
                    //   A new second best is the maximum of the previous best
                    //   (pushed down) and the new logit, never the maximum of
                    //   the running second best alone.
                    //-------------------------------------------------------
                    if(r_first) begin
                        S_zmax  <= r_z[0];
                        S_z2nd  <= 16'h8000;
                        S_imax  <= {CLS_W{1'b0}};
                        r_a     <= 6'd1;
                        r_first <= 1'b0;
                    end
                    else begin
                        if(r_z[r_a] > S_zmax) begin
                            S_zmax <= r_z[r_a];
                            S_z2nd <= S_zmax;           // old best is pushed down
                            S_imax <= r_a[CLS_W-1:0];
                        end
                        else if(r_z[r_a] > S_max2)
                            S_z2nd <= r_z[r_a];

                        // improve4 : C_NOUT is the FULL width class count.
                        //   Writing NOUT[5:0] here would truncate 64 to 0 and
                        //   the scan would stop after the very first clock.
                        if(r_a == C_NOUT - 6'd1) r_state <= ST_CONF;
                        else                     r_a     <= r_a + 6'd1;
                    end
                end

                //-----------------------------------------------------------
                // register the margin so the lookup is a stage of its own
                //-----------------------------------------------------------
                ST_CONF: begin
                    // NOTE with the improve4 seeding both values are equal when
                    // there is only one class, then conf = 0 % (nothing to
                    // compare) which is the honest answer.
                    r_allneg <= S_zmax[15] & ~S_z2nd[15];   // all logits negative
                    r_margin <= S_zmax - S_z2nd;            // 16 bit - 16 bit
                    r_state  <= ST_OUT;
                end

                //-----------------------------------------------------------
                // results   (ST_OUT = 4'd0, does not collide with ST_IDLE
                //            because ST_IDLE is only reachable through here)
                //-----------------------------------------------------------
                ST_OUT: begin
                    O_class <= S_imax;
                    if(r_allneg)
                        O_conf <= 7'd0;
                    else
                        O_conf <= conf_of((|r_margin[18:16]) ? 16'hFFFF
                                                             : r_margin[15:0]);
                    O_valid <= 1'b1;
                    r_state <= ST_IDLE;
                end

                default: r_state <= ST_IDLE;
            endcase
        end
